// t('fedOk', {n:10}) — ถ้าไม่มีคำแปลพม่า จะแสดงไทยแทนอัตโนมัติ
export function t(key, vars) {
  let s = (lang === 'my' ? MY[key] : null) || TH[key] || key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
